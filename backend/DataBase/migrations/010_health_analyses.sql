-- =====================================================================
-- Astra Health · 010 · Health analyses
-- Stores the result of every /analysis call (ML health engine) so that:
--   * the history can show the traffic light of each day without
--     re-analyzing it;
--   * there is a medical record of what the system said and why, even
--     if the model changes later (model_version);
--   * readings synced late (offline) keep their results.
-- Same rules as measurements: insert only, never edited or deleted.
-- Who reads what:
--   crew   -> their own analyses;
--   leader -> their own + the analyses taken while in their crew;
--   admin  -> everything (ground medical team).
-- =====================================================================

create table public.health_analyses (
  -- Same id as the reading that produced it (generated by the client):
  -- resending it hits this key and is never duplicated.
  id               uuid primary key default gen_random_uuid(),
  astronaut_id     uuid not null default auth.uid()
                   references public.profiles (id) on delete cascade,
  day              date not null,                       -- day analyzed
  traffic_light    text not null check (traffic_light in ('green', 'yellow', 'red')),
  mode             text not null check (mode in ('startup', 'personal')),
  clinical_reasons text[] not null default '{}',        -- e.g. 'high temperature'
  deviations       text[] not null default '{}',        -- vs the astronaut's own normal
  connections      text[] not null default '{}',        -- e.g. 'fever speeds up the heart'
  detected_by_ml   boolean not null default false,      -- Isolation Forest flagged it
  model_version    text not null,                       -- which .pkl produced it
  analyzed_at      timestamptz not null default now(),
  -- Snapshot of the astronaut's crew when analyzed (set by trigger).
  crew_id          text references public.crews (id)
                   on update cascade on delete restrict
);

comment on table public.health_analyses is
  'One row per ML analysis. Insert only: the medical record of what the system said and why.';

create index health_analyses_astronaut_day
  on public.health_analyses (astronaut_id, day desc);
create index health_analyses_crew
  on public.health_analyses (crew_id) where crew_id is not null;

-- ---------- Trigger: crew snapshot --------------------------------------
-- Whatever the client sends in crew_id is ignored.

create function public.set_analysis_crew()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  select crew_id into new.crew_id
  from public.profiles where id = new.astronaut_id;
  return new;
end;
$$;

create trigger set_analysis_crew
  before insert on public.health_analyses
  for each row execute function public.set_analysis_crew();

-- Trigger functions are not part of the API (same rule as 004).
revoke execute on function public.set_analysis_crew()
  from public, anon, authenticated;

-- ---------- Security (RLS) ----------------------------------------------

alter table public.health_analyses enable row level security;

revoke all on public.health_analyses from anon, authenticated;
grant select, insert on public.health_analyses to authenticated;  -- no UPDATE or DELETE
grant select, insert, update, delete on public.health_analyses to service_role;

create policy "health_analyses: read own, admin reads all" on public.health_analyses
  for select to authenticated
  using (astronaut_id = (select auth.uid()) or (select public.is_admin()));

create policy "health_analyses: leader reads crew" on public.health_analyses
  for select to authenticated
  using ((select public.is_crew_leader()) and crew_id = (select public.current_crew_id()));

create policy "health_analyses: insert own" on public.health_analyses
  for insert to authenticated
  with check (astronaut_id = (select auth.uid()));

-- ---------- Realtime --------------------------------------------------------
-- New analyses are pushed live (filtered by RLS), like measurements.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables
                     where pubname = 'supabase_realtime'
                       and schemaname = 'public' and tablename = 'health_analyses') then
    alter publication supabase_realtime add table public.health_analyses;
  end if;
end;
$$;
